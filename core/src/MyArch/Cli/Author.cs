    /// <summary>
    /// check: what a plugin's author should know before sharing it. It must
    /// load and render with every theme, in every language it has, with its
    /// settings' defaults; and it should say what it is, in the languages it
    /// has. Errors make it fail; warnings are advice.
    /// </summary>
    internal static int PluginsCheck(string arg)
    {
        var dir = PluginDirOf(arg);
        var errors = new List<string>();
        var warnings = new List<string>();
        Plugin p;
        try
        {
            p = Plugin.Load(dir);
        }
        catch (MyArchException e)
        {
            Console.WriteLine($"{Style.Red}✗{Style.Reset} {e.Message}");
            return 1;
        }
        if (Paths.Base(dir) != p.Id && !IsLink(dir))
            warnings.Add($"its folder is {Paths.Base(dir)}, its id {p.Id}: installed, the folder is named after the id");

        var caps = p.Capabilities();
        if (caps.Count > 0 && caps[0].StartsWith("(unreadable")) errors.Add(caps[0][1..^1]);

        // Its languages: en, and every locales/*.toml.
        var langs = new List<string> { Languages.Fallback };
        var locales = Paths.Join(dir, "locales");
        if (Directory.Exists(locales))
            langs.AddRange(Directory.GetFiles(locales, "*.toml").Select(f => Path.GetFileNameWithoutExtension(f))
                .Where(l => l != Languages.Fallback).Order(StringComparer.Ordinal));
        var en = Paths.Join(locales, Languages.Fallback + ".toml");
        foreach (var lang in langs.Skip(1))
        {
            try
            {
                MyArch.Locale.Catalog.Load(p.Id, dir, lang);
                var own = Toml.ReadFile(Paths.Join(locales, lang + ".toml")) ?? new();
                var missing = new List<string>();
                if (!own.ContainsKey("plugin.name")) missing.Add("plugin.name");
                if (!own.ContainsKey("plugin.description")) missing.Add("plugin.description");
                foreach (var k in p.Settings.Keys.Order(StringComparer.Ordinal))
                    if (!own.ContainsKey("setting." + k)) missing.Add("setting." + k);
                if (File.Exists(en))
                    foreach (var k in (Toml.ReadFile(en) ?? new()).Keys.Order(StringComparer.Ordinal))
                        if (!own.ContainsKey(k)) missing.Add(k);
                if (missing.Count > 0)
                    warnings.Add($"locales/{lang}.toml: in English still: {string.Join(", ", missing)}");
            }
            catch (MyArchException e)
            {
                errors.Add(e.Message);
            }
        }
        if (langs.Count == 1)
            warnings.Add("only in English: a locales/es.toml (plugin.name, plugin.description, setting.KEY…) puts it in Spanish");

        // What it needs, as installed here, and it in its place.
        var (all, broken) = Plugin.Discover(PluginDirs());
        var set = new Dictionary<string, Plugin> { [p.Id] = p };
        var queue = new Queue<Plugin>([p]);
        while (queue.Count > 0)
            foreach (var r in queue.Dequeue().Meta.Requires)
            {
                Requirement req;
                try
                {
                    req = Requirement.Parse(r);
                }
                catch (MyArchException e)
                {
                    errors.Add(e.Message);
                    continue;
                }
                if (set.ContainsKey(req.Id)) continue;
                if (all.FirstOrDefault(x => x.Id == req.Id) is { } dep)
                {
                    set[req.Id] = dep;
                    queue.Enqueue(dep);
                }
                else errors.Add($"needs {req.Id}, which isn't here" + (broken.TryGetValue(req.Id, out var why) ? $": {why}" : ""));
            }
        var problems = Dependencies.Unmet(set.Values, set.Values, broken).Where(x => x.Plugin == p.Id).Select(x => x.Text).ToList();
        errors.AddRange(problems);

        // Every theme, every language, with the defaults: what it renders to
        // must not depend on the theme or language its author uses.
        var themes = Theme.List(ThemeDirs());
        var renders = 0;
        // The same mistake in every theme is said once: where, and how many more.
        var failed = new List<(string Where, string Text, string Key)>();
        if (errors.Count == 0)
            foreach (var tid in themes)
            {
                var t = Theme.Load(ThemeDirs(), tid);
                foreach (var lang in langs)
                {
                    try
                    {
                        var output = Renderer.All([.. set.Values], t, _ => null, lang);
                        renders++;
                        foreach (var f in output.Files.Where(f => f.Plugin == p.Id && f.Content.Trim() == ""))
                            warnings.Add($"{Tilde(f.Path)} renders empty (theme {tid}, {lang})");
                    }
                    catch (MyArchException e)
                    {
                        failed.Add(($"theme {tid}, {lang}", e.Message, e.Message.Replace($"\"{tid}\"", "\"…\"")));
                    }
                }
            }

        foreach (var g in failed.GroupBy(f => f.Key))
            errors.Add($"{g.First().Where}{(g.Count() > 1 ? $" (and {g.Count() - 1} more)" : "")}: {g.First().Text}");

        if (p.Meta.Description == "") warnings.Add("no description: [plugin] description = \"…\", one line on what it does");
        if (p.Meta.Categories.Count == 0)
            warnings.Add($"no categories: taken for {string.Join(", ", p.CategoriesOrGuess())}; say it (categories = [\"{p.CategoriesOrGuess()[0]}\"])");
        if (!Directory.GetFiles(dir).Any(f => Paths.Base(f).Equals("README.md", StringComparison.OrdinalIgnoreCase)))
            warnings.Add("no README.md: its page in the Plugins panel is empty");
        foreach (var k in p.Settings.Keys.Order(StringComparer.Ordinal))
            if ((p.SettingsInfo.GetValueOrDefault(k)?.Description ?? "") == "")
                warnings.Add($"setting {k}: no description (a # comment above it in plugin.toml)");
        if (p.Targets.Any(t => t.System) && p.Hardware == null)
            errors.Add("writes system files, but has no [hardware] rules");

        foreach (var e in errors.Distinct()) Console.WriteLine($"{Style.Red}✗{Style.Reset} {e}");
        foreach (var w in warnings.Distinct()) Console.WriteLine($"{Style.Amber}!{Style.Reset} {w}");
        Console.WriteLine($"{p.Id} {p.Meta.Version}: {Plural(renders, "render", "renders")} ({themes.Count} themes × {string.Join(", ", langs)}), " +
            $"{Plural(caps.Count, "capability", "capabilities")}, {Plural(errors.Distinct().Count(), "error", "errors")}, {Plural(warnings.Distinct().Count(), "warning", "warnings")}");
        if (errors.Count == 0)
        {
            Console.WriteLine("\nIt would be able to:");
            foreach (var cap in caps) Console.WriteLine($"  - {cap}");
        }
        return errors.Count > 0 ? 1 : 0;
    }

    /// <summary>A plugin's folder: DIR (with a plugin.toml), or an installed plugin's id; "" is the current folder.</summary>
    static string PluginDirOf(string arg)
    {
        if (arg == "") arg = ".";
        var d = Paths.ExpandHome(arg);
        if (File.Exists(Paths.Join(d, "plugin.toml"))) return Path.GetFullPath(d);
        if (Plugin.IdPattern().IsMatch(arg) && Plugin.Discover(PluginDirs()).Plugins.FirstOrDefault(p => p.Id == arg) is { } p) return p.Dir;
        throw new MyArchException(arg == "." ? "no plugin.toml here: myarch plugins check ID|DIR" : $"no plugin \"{arg}\" (an id, or a folder with a plugin.toml)");
    }

