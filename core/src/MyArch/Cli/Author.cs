    private static partial System.Text.RegularExpressions.Regex ShellLogLine();

    /// <summary>
    /// The running shell's warnings about these files since a time (its
    /// reloads are numbered by the time, in ms): a QML mistake shows only
    /// when the shell loads the file.
    /// </summary>
    static List<string> ShellWarnings(List<string> files, long sinceMs)
    {
        string log;
        try
        {
            using var proc = System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo("sh",
                ["-c", "pid=$(pgrep -n -f '^qs -c myarch') && exec qs log --pid \"$pid\" -t 400"])
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
            })!;
            log = proc.StandardOutput.ReadToEnd();
            proc.WaitForExit();
        }
        catch (Exception e) when (e is System.ComponentModel.Win32Exception or IOException)
        {
            return [];
        }
        var out_ = new List<string>();
        foreach (var raw in log.Split('\n'))
        {
            var m = ShellLogLine().Match(Ansi().Replace(raw, ""));
            if (!m.Success || !files.Contains(m.Groups["file"].Value) || long.Parse(m.Groups["gen"].Value) < sinceMs) continue;
            var w = $"{Tilde(m.Groups["file"].Value)}:{m.Groups["line"].Value}: {m.Groups["text"].Value.Trim()}";
            if (!out_.Contains(w)) out_.Add(w);
        }
        return out_;
    }

    /// <summary>What the plugin's files are now: names, sizes and times (not .git).</summary>
    static string Fingerprint(string dir)
    {
        var sb = new System.Text.StringBuilder();
        try
        {
            foreach (var f in Directory.EnumerateFiles(dir, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
            {
                if (f.Contains("/.git/")) continue;
                var fi = new FileInfo(f);
                sb.Append(f).Append('\0').Append(fi.Length).Append('\0').Append(fi.LastWriteTimeUtc.Ticks).Append('\n');
            }
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            sb.Append(e.Message); // mid-save: tried again
        }
        return sb.ToString();
    }

