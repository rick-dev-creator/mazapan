    /// <summary>
    /// fork: a built-in plugin copied into the plugin folder, to change: the
    /// copy takes its place. With NEW, a copy under another id, next to it
    /// (from git too): a plugin to start from.
    /// </summary>
    internal static void PluginsFork(string id, string newId)
    {
        var c = Catalog.Load();
        var p = c.Find(id) ?? throw new MyArchException(c.Broken.GetValueOrDefault(id) ?? $"no plugin \"{id}\"");
        var builtIn = c.Origin(p) == "built-in";
        if (newId == "")
        {
            if (!builtIn) throw new MyArchException($"{id} is {c.Origin(p)}: it's yours to change already, or give the copy a new id: myarch plugins fork {id} NEW");
            newId = id;
        }
        else if (!Plugin.IdPattern().IsMatch(newId)) throw new MyArchException($"plugin id \"{newId}\": lowercase letters, digits and dashes");
        else if (newId != id && c.Find(newId) != null) throw new MyArchException($"there's a plugin {newId} already");
        if (p.Hardware != null && newId == id)
            Console.WriteLine($"{Style.Amber}a hardware plugin: myarch apply --system writes what you change, as root{Style.Reset}");
        var to = Paths.Join(Git.Dir, newId);
        if (Paths.Exists(to)) throw new MyArchException($"{Tilde(to)} is already there");
        CopyTree(p.Dir, to);
        if (newId != id)
        {
            var manifest = Paths.Join(to, "plugin.toml");
            var text = File.ReadAllText(manifest);
            var renamed = System.Text.RegularExpressions.Regex.Replace(text, "(?m)^(id\\s*=\\s*)\"" + id + "\"", "$1\"" + newId + "\"");
            File.WriteAllText(manifest, renamed, Files.Utf8);
            Console.WriteLine($"copied {id} to {Tilde(to)} as {newId}");
            // Both would write the same files: the copy's are for it to change.
            if (c.Cfg.IsOn(p) && p.Targets.Count > 0 && Dependencies.Dependents(id, c.Enabled()).Count == 0)
            {
                c.Cfg.TurnOff(p);
                c.Cfg.Save();
                Console.WriteLine($"turned {id} off: both would write {string.Join(", ", p.Targets.Select(t => t.Output).Take(2))}…; change {newId}'s outputs to have both");
            }
            else if (p.Targets.Count > 0)
                Console.WriteLine($"{Style.Amber}change {newId}'s outputs: {id} writes the same files{Style.Reset}");
        }
        else
            Console.WriteLine($"""
                copied {id} to {Tilde(to)}: your copy takes the built-in's place
                  myarch plugins dev {id}    apply it on every save
                  myarch plugins diff {id}   what you've changed
                  delete {Tilde(to)} to go back to the built-in
                """);
    }

    /// <summary>A folder copied, files only: no links, no .git.</summary>
    static void CopyTree(string from, string to)
    {
        Files.CreateDirectory(to);
        foreach (var e in Directory.EnumerateFileSystemEntries(from))
        {
            var name = Paths.Base(e);
            if (name == ".git" || new FileInfo(e).LinkTarget != null) continue;
            if (Directory.Exists(e)) CopyTree(e, Paths.Join(to, name));
            else File.Copy(e, Paths.Join(to, name));
        }
    }

    /// <summary>diff: what a fork changed from the built-in plugin it takes the place of.</summary>
    internal static void PluginsDiff(string id)
    {
        if (!Plugin.IdPattern().IsMatch(id)) throw new MyArchException($"plugin id \"{id}\": lowercase letters, digits and dashes");
        var mine = Paths.Join(Git.Dir, id);
        var theirs = Paths.Join(Root(), "plugins", id);
        if (!Directory.Exists(mine) || !Directory.Exists(theirs))
            throw new MyArchException($"{id} isn't a fork of a built-in plugin (myarch plugins fork {id})");
        static IEnumerable<string> Rel(string root) => Directory.Exists(root)
            ? Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories).Select(f => Path.GetRelativePath(root, f)).Where(f => !f.StartsWith(".git/"))
            : [];
        var any = false;
        foreach (var rel in Rel(theirs).Union(Rel(mine)).Order(StringComparer.Ordinal))
        {
            var a = Paths.Join(theirs, rel);
            var b = Paths.Join(mine, rel);
            var ta = File.Exists(a) ? File.ReadAllText(a) : "";
            var tb = File.Exists(b) ? File.ReadAllText(b) : "";
            if (ta == tb) continue;
            any = true;
            Console.Write(Diff.Unified(ta, tb, File.Exists(a) ? "built-in/" + rel : "/dev/null", File.Exists(b) ? "yours/" + rel : "/dev/null"));
        }
        if (!any) Console.WriteLine($"{id}: the same as the built-in");
    }
