    /// <summary>new: a working plugin of a kind, to change into what one wants; in the plugin folder (on at once), or in DIR.</summary>
    internal static void PluginsNew(string id, string kind, string dir)
    {
        if (!Plugin.IdPattern().IsMatch(id)) throw new MyArchException($"plugin id \"{id}\": lowercase letters, digits and dashes");
        if (kind == "")
            kind = id.StartsWith("bar-") ? "bar" : id.StartsWith("theme-") ? "theme" : id.StartsWith("hypr-") ? "window" : "tools";
        if (!Kinds.Contains(kind)) throw new MyArchException($"--kind {kind}: one of {string.Join(", ", Kinds)}");
        var inPlace = dir == "";
        var to = inPlace ? Paths.Join(Git.Dir, id) : Path.GetFullPath(Paths.ExpandHome(dir));
        if (Paths.Exists(to) && (!Directory.Exists(to) || Directory.EnumerateFileSystemEntries(to).Any()))
            throw new MyArchException($"{Tilde(to)} is already there");
        if (inPlace && Plugin.Discover(PluginDirs()).Plugins.FirstOrDefault(p => p.Id == id) is { } there)
            throw new MyArchException($"there's a plugin {id} already ({Tilde(there.Dir)})" +
                (Paths.Dir(there.Dir) == Paths.Join(Root(), "plugins") ? $": to change it, myarch plugins fork {id}" : ""));
        var name = Humanize(id);
        foreach (var (rel, text) in Scaffold(kind, id))
        {
            var path = Paths.Join(to, rel);
            Files.CreateDirectory(Paths.Dir(path));
            File.WriteAllText(path, text.Replace("@ID@", id).Replace("@NAME@", name).Replace("@APP@", AppOf(id)), Files.Utf8);
        }
        Console.WriteLine($"created {Tilde(to)}: a {kind} plugin");
        foreach (var f in Directory.GetFiles(to, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
            Console.WriteLine("  " + Path.GetRelativePath(to, f));
        var at = inPlace ? id : Tilde(to);
        Console.WriteLine($"""

            next:
              myarch plugins dev {at}     apply it on every save, while you change it
              myarch plugins check {at}   before sharing it: every theme, every language
            """);
    }

    /// <summary>font-size-picker -> "Font size picker" (bar- and friends dropped).</summary>
    static string Humanize(string id)
    {
        foreach (var pre in new[] { "bar-", "theme-", "hypr-" })
            if (id.StartsWith(pre) && id.Length > pre.Length) id = id[pre.Length..];
        var s = id.Replace('-', ' ');
        return char.ToUpperInvariant(s[0]) + s[1..];
    }

    static string AppOf(string id) => id.StartsWith("theme-") && id.Length > 6 ? id[6..] : id;

