    /// <summary>
    /// dev: the plugin applied again whenever one of its files changes, until
    /// Ctrl+C. A folder elsewhere (the plugin's own repository) is linked
    /// into the plugin folder first, and stays linked: myarch plugins remove
    /// ID takes the link away, not the folder.
    /// </summary>
    static void PluginsDev(string arg)
    {
        var dir = PluginDirOf(arg);
        var p = Plugin.Load(dir);
        var place = Paths.Join(Git.Dir, p.Id);
        if (Paths.Dir(dir) == Paths.Join(Root(), "plugins"))
            throw new MyArchException($"{p.Id} is built in: to change it, myarch plugins fork {p.Id}, then myarch plugins dev {p.Id}");
        if (PluginsLock.Load().Get(p.Id) != null)
            throw new MyArchException($"{p.Id} is installed from git: work on your clone of it (myarch plugins dev ~/src/{p.Id}), after myarch plugins remove {p.Id}");
        if (p.Hardware != null || p.Targets.Any(t => t.System))
            throw new MyArchException($"{p.Id} is a hardware plugin: check it with myarch plugins check, apply it with myarch apply --system");
        if (Path.GetFullPath(dir) != Path.GetFullPath(place))
        {
            if (new FileInfo(place).LinkTarget is { } target)
            {
                if (Path.GetFullPath(target, Git.Dir) != Path.GetFullPath(dir))
                    throw new MyArchException($"{Tilde(place)} is a link to {target} already: myarch plugins remove {p.Id} first");
            }
            else if (Paths.Exists(place))
                throw new MyArchException($"there's a plugin {p.Id} in {Tilde(place)} already");
            else
            {
                if (Plugin.Discover([Paths.Join(Root(), "plugins")]).Plugins.Any(b => b.Id == p.Id))
                    Console.WriteLine($"{Style.Amber}it takes the built-in {p.Id}'s place while linked{Style.Reset}");
                Files.CreateDirectory(Git.Dir);
                Directory.CreateSymbolicLink(place, dir);
                Console.WriteLine($"linked {Tilde(place)} -> {Tilde(dir)} (myarch plugins remove {p.Id} unlinks it)");
            }
        }
        var cfg = Settings.Load();
        if (!cfg.IsOn(p))
        {
            cfg.TurnOn(p);
            cfg.Save();
            Console.WriteLine($"turned {p.Id} on");
        }
        noSnapshots = true;
        Console.WriteLine($"{Style.Dim}applying {p.Id} on every save, without undo snapshots; Ctrl+C to stop{Style.Reset}");
        string? seen = null;
        while (true)
        {
            var now = Fingerprint(dir);
            if (now != seen)
            {
                // Saving writes a file or several: wait for them to settle.
                Thread.Sleep(150);
                now = Fingerprint(dir);
                seen = now;
                Console.WriteLine($"\n{Style.Bold}{DateTime.Now:HH:mm:ss}{Style.Reset} {p.Id}");
                var since = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                try
                {
                    CmdApply(["--changes-only"]);
                    // What the shell says of its QML, once it has loaded it.
                    var qml = QmlOutputs(dir);
                    if (qml.Count > 0)
                    {
                        Thread.Sleep(1500);
                        foreach (var w in ShellWarnings(qml, since)) Console.WriteLine($"{Style.Red}✗{Style.Reset} {w}");
                    }
                }
                // Whatever this save got wrong (a file that isn't myarch's in the
                // way, too), the next save tries again.
                catch (Exception e) when (e is MyArchException or Applying.ConflictException or IOException or UnauthorizedAccessException)
                {
                    Console.WriteLine($"{Style.Red}✗{Style.Reset} {e.Message}");
                }
            }
            Thread.Sleep(300);
        }
    }

    /// <summary>The plugin's QML files, where they're written (read again: the manifest may have changed).</summary>
    static List<string> QmlOutputs(string dir)
    {
        try
        {
            return Plugin.Load(dir).Targets.Where(t => t.Each.Count == 0 && t.Output.EndsWith(".qml"))
                .Select(t => Paths.ExpandHome(t.Output)).ToList();
        }
        catch (MyArchException)
        {
            return [];
        }
    }

