    // A JSON file that doesn't parse is never rewritten blind; a busy one
    // (its app running) isn't touched at all.
    [Fact]
    public void UnreadableAndBusy()
    {
        var p = dir["Preferences"];
        Write(p, "{\"a\":1,}");
        System.IO.File.SetUnixFileMode(p, UnixFileMode.UserRead | UnixFileMode.UserWrite);
        var f = new RenderedFile { Plugin = "p", Path = p, Content = "{\"x\":1}", Merge = "json" };
        var (ch, orphans) = Plan(new Owned(), f);
        Assert.Equal(State.Unreadable, ch[0].State);
        Apply.Execute(ch, orphans, new Owned(), true);
        Assert.Equal("{\"a\":1,}", ReadText(p)); // untouched, even with --adopt
        Write(p, "{\"a\":1}");
        f.Busy = true;
        var owned = new Owned { [p] = "json:old" };
        (ch, orphans) = Plan(owned, f);
        Assert.Equal(State.Busy, ch[0].State);
        Apply.Execute(ch, orphans, owned, false);
        Assert.Equal("{\"a\":1}", ReadText(p));
        Assert.Equal("json:old", owned[p]);
        // Rewritten, a 0600 file stays 0600.
        f.Busy = false;
        (ch, orphans) = Plan(new Owned(), f);
        Apply.Execute(ch, orphans, new Owned(), false);
        Assert.Equal("{\"a\":1,\"x\":1}", ReadText(p));
        Assert.Equal(UnixFileMode.UserRead | UnixFileMode.UserWrite, System.IO.File.GetUnixFileMode(p));
    }

