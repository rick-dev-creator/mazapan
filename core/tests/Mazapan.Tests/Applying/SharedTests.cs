    // A shared file kept in a dotfiles repo, linked from ~/.config: written
    // through the link, which stays a link.
    [Fact]
    public void SharedFileThroughSymlink()
    {
        string real = dir["dotfiles-kdeglobals"], link = dir["kdeglobals"];
        Write(real, "[General]\nx=1\n");
        System.IO.File.CreateSymbolicLink(link, real);
        var owned = new Owned();
        var (ch, orphans) = Plan(owned, Shared(link, "[KDE]\nwidgetStyle=Fusion\n"));
        Apply.Execute(ch, orphans, owned, false);
        Assert.NotNull(new FileInfo(link).LinkTarget); // the link was not replaced by a file
        var b = ReadText(real);
        Assert.Contains("widgetStyle=Fusion", b);
        Assert.Contains("x=1", b);
    }

    // A file owned whole by an older version, then rewritten by the app, is
    // merged into, not a conflict; and a shared orphan stays.
    [Fact]
    public void SharedFileFromWholeAndOrphan()
    {
        var p = dir["qt6ct.conf"];
        Write(p, "[Appearance]\nstyle=Fusion\n[SettingsWindow]\ngeometry=x\n");
        var owned = new Owned { [p] = Apply.Sum("# old\n[Appearance]\nstyle=Fusion\n") };
        var (ch, orphans) = Plan(owned, Shared(p, "[Appearance]\nstyle=Fusion\nicon_theme=A\n"));
        Assert.Equal(State.Changed, ch[0].State);
        Apply.Execute(ch, orphans, owned, false);
        (ch, orphans) = Plan(owned);
        var res = Apply.Execute(ch, orphans, owned, false);
        Assert.True(System.IO.File.Exists(p)); // a shared file stays when its plugin goes
        Assert.Single(res.Shared);
    }

    [Fact]
    public void SharedOwnedRoundTrips()
    {
        var keys = Apply.IniKeys("[b]\nk=2\n[a]\nk=1\n");
        var s = Apply.SharedOwned("ini", keys);
        Assert.Equal("ini:a\0k\01\nb\0k\02", s);
        Assert.True(Apply.FromSharedOwned(s, out var back, out var format));
        Assert.Equal("ini", format);
        Assert.Equal(keys.OrderBy(kv => kv.Key), back.OrderBy(kv => kv.Key));
        Assert.False(Apply.IsShared(Apply.Sum("x")));
    }
